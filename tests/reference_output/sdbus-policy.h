Policy::VTable &
Policy::VTable::addImplementor( Implementor::SharedPtr theNewImplementor ) {
  
  if ( ! isSignalInterface) {
    Policy::reportError( EINVAL, 
			 "Attempt to register signal interface %s "
			 "when it is already registered as method interface",
			 itsInterfaceName.c_str() );
  }

  itsImplementors.emplace_back( theNewImplementor );
  itsSignalCounter = 0;
  return *this;
}

//=============================================================================
std::size_t
Policy::VTable::removeImplementor( const Implementor * const theOneToRemove ) {
  
  const auto theInitialNoOfImplementors = itsImplementors.size();
  
  auto theIterator = itsImplementors.begin();
  
  do {
      const Implementor::SharedPtr theShared( theIterator->lock() );

      theIterator = 
              (!theShared || (theShared.get() == theOneToRemove)) 
                ? itsImplementors.erase(theIterator)
                : (theIterator + 1);
      
  } while (theIterator != itsImplementors.end());
  
  const auto theFinalNoOfImplementors = itsImplementors.size();
  
  if (theFinalNoOfImplementors < theInitialNoOfImplementors) {
    return theFinalNoOfImplementors;
  }
  else {
    Policy::reportError( EINVAL,
			 "Failed to erase implementor of %s",
			 itsInterfaceName.c_str() );
  }
}

