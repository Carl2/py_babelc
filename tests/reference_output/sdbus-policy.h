// A class to convey the dbus error name and description from
// sd_dbus_error>s received over the wire.
//
struct DbusError {
    virtual const std::string &getMessage() const = 0;
    virtual const std::string &getName()    const = 0;
protected:
    virtual ~DbusError() {}
};

template <class Exception>
struct DbusErrorException : DbusError, Exception {
    DbusErrorException() : 
      DbusError{}, 
      Exception{}, 
      itsName{}, 
      itsMessage{} {}

    DbusErrorException( const sd_bus_error &theError ) :
      DbusError{},
      Exception{ theError.message },
      itsName{ theError.name },
      itsMessage{ theError.message } {}
    
    DbusErrorException( const std::string &theMessage, const std::string &theName = std::string{}) :
      DbusError{},
      Exception{ theMessage },
      itsName{ theName },
      itsMessage{ theMessage } {}
  
    virtual const std::string &getMessage() const override { return itsMessage; }
    virtual const std::string &getName()    const override { return itsName; }
 
private:
    const std::string itsName;
    const std::string itsMessage;
};

