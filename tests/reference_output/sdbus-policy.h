void 
Policy::runMainLoop( std::chrono::high_resolution_clock::duration  theDuration ) {
   namespace chrono = std::chrono;
   using     hrc    = std::chrono::high_resolution_clock;
    
   const auto theStopTime = hrc::now() + theDuration;
  
    while (!itsStopEventLoopFlag) {

        if (itsBusNameIsRequested == BusNameStatus::No) {
          bool requestIsMade = false;

           for (const auto &i : itsImplementors) {
              requestIsMade = i.second->requestBusnameForSignalInterface() || requestIsMade;
           }

           itsBusNameIsRequested = requestIsMade ? BusNameStatus::Yes : BusNameStatus::No;
        }

        const auto theProcessStatus = sd_bus_process( itsBus.get(), NULL );
        
        if (itsStopEventLoopFlag) {
           return;
        }

        COM_SEASWORD_SDBUS_CHECK( theProcessStatus );

	uint64_t theSleepDuration;

	if (theDuration == hrc::duration::max()) {
	  theSleepDuration = static_cast<uint64_t>(-1);
	}
	else {
	  const auto now = hrc::now();

	  if (now >= theStopTime) {
	    return;
	  }

	  theSleepDuration = 
	    chrono::duration_cast<chrono::microseconds>(theStopTime - now).count();
	}

        if (theProcessStatus == 0) { 
            const auto theWaitStatus = sd_bus_wait( itsBus.get(), theSleepDuration );
            
            COM_SEASWORD_SDBUS_CHECK( theWaitStatus );
        }
    }
}

//=============================================================================

void 
Policy::stopMainLoop() {
   itsStopEventLoopFlag = true;
}

//=============================================================================

void
Policy::processEvents() {
   while (processEvent() == EventQueue::HasMoreEvents) {
      // Just continue
   }
}

//=============================================================================

Policy::EventQueue 
Policy::processEvent() {
   if (itsStopEventLoopFlag) {
      return EventQueue::IsStopped;
   }
   else {
      if (itsBusNameIsRequested == BusNameStatus::No) {
         bool requestIsMade = false;
         
         for (const auto &i : itsImplementors) {
            requestIsMade = i.second->requestBusnameForSignalInterface() || requestIsMade;
         }

         itsBusNameIsRequested = requestIsMade ? BusNameStatus::Yes : BusNameStatus::No;
      }

      const auto theProcessStatus = sd_bus_process( itsBus.get(), NULL );
        
      if (itsStopEventLoopFlag) {
         return EventQueue::IsStopped;
      }

      COM_SEASWORD_SDBUS_CHECK( theProcessStatus );

      if (theProcessStatus == 0) {
         return EventQueue::IsEmpty;
      }
      else {
         return EventQueue::HasMoreEvents;
      }
   }
}

