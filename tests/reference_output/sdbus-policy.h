void Policy::requestBusName() {

    if (itsBusNameIsRequested == BusNameStatus::No) {
        const int theError = sd_bus_request_name( itsBus.get(), itsBusName.c_str(), 0 );
        if (theError < 0) {
            Policy::reportError( -theError, "Failed to acquire busname '%s', errno %d", 
                           itsBusName.c_str(), -theError);
        }       
        itsBusNameIsRequested = BusNameStatus::Yes;
    }
}

