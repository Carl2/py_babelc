Policy::VTable &
Policy::VTable::addMethod( 
    const char                                  *theMethodName,
    const char                                  *theReturnType,
    const char                                  *theSignature,
    const typename Implementor::MessageCallback &theCallback ) {

    using RawHandlerTable = RawHandler<32>;

    if (itsImplementors.size() > 1) {
      // This is a multiple listener VTable. Only do checks.
      //
      if ( ! isSignalInterface ) {
	Policy::reportError( EINVAL, 
			     "Trying to multiply publish method interface %s",
			     itsInterfaceName.c_str() );
      }

      if (itsSignalCounter >= itsSignalCallbacks.size()) {
	Policy::reportError( EINVAL, 
			     "Trying to publish signal interface %s with "
			     "more than " SIZE_TF " signals",
			     itsInterfaceName.c_str(),
			     itsSignalCallbacks.size() );
      }
      
      const sd_bus_vtable &thisItem = itsSdbusVTable[itsSignalCounter+1];

      if (strcmp(thisItem.x.signal.member,theMethodName) || 
	  strcmp(thisItem.x.signal.signature, theSignature)) {
	Policy::reportError( EINVAL, 
			     "Trying to publish signal %s::%s(%s) when "
			     "%s::%s(%s) was expected",
			     itsInterfaceName.c_str(),
			     theMethodName,
			     theSignature,
			     itsInterfaceName.c_str(),
			     thisItem.x.signal.member,
			     thisItem.x.signal.signature );
      }
      
      itsSignalCounter += 1;
    }
    else {
      if (itsVTable.size() >= RawHandlerTable::value.size()) {
        Policy::reportError( EDOM, "Max # of methods reached for %s", 
                             itsInterfaceName.c_str() );
      }

      const sd_bus_message_handler_t theRawMethod = 
        RawHandlerTable::value[itsVTable.size()];

      itsSdbusVTable.resize(itsSdbusVTable.size() + 1);

      {
        sd_bus_vtable &theNewItem = itsSdbusVTable.back();

        memset(&theNewItem, 0, sizeof (theNewItem));

        if (isSignalInterface) {
	  theNewItem.type               = _SD_BUS_VTABLE_SIGNAL;
	  theNewItem.x.signal.member    = theMethodName;
	  theNewItem.x.signal.signature = theSignature;
	  itsSignalCallbacks.push_back(theRawMethod);
        }
        else {
	  // Only methods have a non-nullptr return type
	  //
	  theNewItem.type               = _SD_BUS_VTABLE_METHOD;
          theNewItem.flags              = SD_BUS_VTABLE_UNPRIVILEGED;
	  theNewItem.x.method.member    = theMethodName;
	  theNewItem.x.method.signature = theSignature;
	  theNewItem.x.method.result    = theReturnType;
	  theNewItem.x.method.handler   = theRawMethod;

          if ((theReturnType == nullptr) || (*theReturnType == '\0')) {
             theNewItem.flags |= SD_BUS_VTABLE_METHOD_NO_REPLY;
          }

        } 
      }

      itsVTable.push_back(theCallback);
    }
    return *this;
}


