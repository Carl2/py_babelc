template <typename MessageT>
Policy::Message 
Policy::sendMessage( MessageT &&theMessage ) {
    sd_bus_error    theError          = SD_BUS_ERROR_NULL;
    sd_bus_message *theRawReturnValue = nullptr;

    const auto theCallStatus = sd_bus_call( 
        itsBus.get(),
        theMessage.get(),
        (uint64_t)-1,
        &theError,
        &theRawReturnValue
    );

    Message theReturnValue( theRawReturnValue );

    itsNotification( shared_from_this() );

    if (theCallStatus < 0) {
        throwError( theError );
    }

    return theReturnValue;
}

