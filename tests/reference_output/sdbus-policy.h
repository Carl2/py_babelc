inline std::shared_ptr<Policy> 
Policy::createPolicy( Sdbus                forTheBus, 
                      const char          *theBusName,
                      NotifyPendingEvents  theNotification ) {
    sd_bus *theRawBus;

    switch (forTheBus) {
    case Sdbus::System:
        COM_SEASWORD_SDBUS_CHECK(sd_bus_open_system(&theRawBus));
        break;
    case Sdbus::Session:
        COM_SEASWORD_SDBUS_CHECK(sd_bus_open_user(&theRawBus));
        break;
    default:
        COM_SEASWORD_SDBUS_CHECK( -1 );
    }            
    
    // The ownership (and subsequent sd_bus_unref) is handled by
    // the Bus unique pointer
    //
    Bus theBus( theRawBus );


    return std::shared_ptr<Policy>( 
               new Policy(theBus, theBusName, theNotification  ) 
           );

}



