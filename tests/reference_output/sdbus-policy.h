//=============================================================================
// Alright, here is the main policy class used by the babelc generated ipc 
// code. The generated code will never create or copy instances, but better 
// safe than sorry and delete unwanted constructors, assignment and maybe make 
// the needed constructors private.
// Required members are marked in the comment field with REQUIRED.
//
struct Policy : std::enable_shared_from_this<Policy> {
    //-------------------------------------------------------------------------
    // REQUIRED
    // The generated code relies upon that a Message type exists. It is never
    // used for more than creating, sending and receiving messages and no 
    // properties are assumed. An instance of this type is never kept in a 
    // static scope by the generated code.
    //
    using Message = std::unique_ptr<
                        sd_bus_message, 
                        ManagedReleaser<sd_bus_message, sd_bus_message_unref > 
                    >;
   
    //-------------------------------------------------------------------------
    // REQUIRED
    // The generated code relies upon that a Boolean type exists, 
    // which has default value 0 (false) and is non-zero when true.
    // The generated code will always use this type when the C++
    // code it is generated from uses an ordinary 'bool'.
    //
    enum struct Boolean : std::uint32_t {};

    //-------------------------------------------------------------------------
    // OPTIONAL
    // You can declare special types which may be used via the C++ attribute
    // [[babelc::ipc_type("<typename>") to force special handling of a type.
    // Typically this will be used when the underlying type is already an
    // existing C++ type (e.g. a file descriptor or an object path as below, 
    // where the value is a signed 32 bit integer compatible type or a string 
    // respectively.
    // See the User Guide for comments on this.
    
    struct FileDescriptor {
      template <bool IsEnum, typename TypeToCheck, typename BaseType>
        struct Checker {
          static constexpr bool value = std::is_same< TypeToCheck, BaseType >::value; 
        };

      template <typename TypeToCheck, typename BaseType>
        struct Checker<true,TypeToCheck,BaseType> {
          static constexpr bool value = std::is_same< std::underlying_type_t<TypeToCheck>, BaseType >::value; 
        };

      template <typename TypeToCheck>
      using Compatible = Checker< std::is_enum<TypeToCheck>::value, TypeToCheck, std::int32_t >;

      using value_type = std::int32_t;

      template <typename T>
      static std::enable_if_t<Compatible<T>::value>
      IpcReadContainer( const Message &fromTheMessage, T &theValue );

      template <typename T>
      static std::enable_if_t<Compatible<T>::value>
      IpcWriteContainer( const Message &fromTheMessage, const T &theValue );
    };
   
    struct Object {
      using value_type = const char *;

      template <typename TypeToCheck>
      using Compatible = std::is_same<std::string,TypeToCheck>;

      template <typename T>
      static std::enable_if_t<Compatible<T>::value>
      IpcReadContainer( const Message &fromTheMessage, T &theValue );

      template <typename T>
      static std::enable_if_t<Compatible<T>::value>
      IpcWriteContainer( const Message &fromTheMessage, const T &theValue );
    };
   
    //-------------------------------------------------------------------------
    // OPTIONAL
    // If you intend to use std::variant or boost::variant this type must
    // be defined.
    // See the User Guide for comments on this.
    
    struct VariantType {
    };

    //-------------------------------------------------------------------------
    // REQUIRED
    // The generated code will use this RAII class to encapsulate the reading
    // of a container (structure or array of non-simple types). The only thing
    // used of the structure is the constructor.
    //
    template <typename  theContainerType>
    struct ReadContainerScope {
        explicit ReadContainerScope( Message &forTheMessage, bool anonymousContents );
        ~ReadContainerScope();
        const Message &itsMessage;
    };
    
    //-------------------------------------------------------------------------
    // OPTIONAL
    // The same as the one above except that this is used for reading a 
    // variant record (std::variant or boost::variant).
    //
    template <typename notUsedNow = void>
    struct ReadVariantScope {
        explicit ReadVariantScope( Message &forTheMessage );

        ~ReadVariantScope();

        template <typename typeToCheck>
        bool containsType() const;

        const Message &itsMessage;
    };

    //-------------------------------------------------------------------------
    // REQUIRED
    // The same as the one above except that this is used for writing a 
    // container.
    //
    template <typename theContainerType>
    struct WriteContainerScope {
        explicit WriteContainerScope( Message &forTheMessage );
        ~WriteContainerScope();
        const Message &itsMessage;
    };

    //-------------------------------------------------------------------------
    // OPTIONAL
    // The same as the one above except that this is used for writing a 
    // variant record (std::variant or boost::variant).
    //
    template <typename theContainedType>
    struct WriteVariantScope {
        explicit WriteVariantScope( Message &forTheMessage );
        ~WriteVariantScope();
        const Message &itsMessage;
    };

    //-------------------------------------------------------------------------
    // REQUIRED
    // Query method to see if there is more in a container.
    //
    [[gnu::weak]]
    static bool AtEndOfContainer ( const Message &inTheMessage )
      ;

    //-------------------------------------------------------------------------
    // REQUIRED
    // A generated class that intends to register itself as receiver of messages
    // will always inherit from the following class. The generated code expects
    // nothing more than the shared pointer declaration and the message callback 
    // type. 
    // The message callback, when invoked, should contain the same implementor
    // pointer that was used during registration.The return value should be
    // initialized to an empty message where the return value may be filled in.
    // If the method declared no return values during its addition to the 
    // VTable (see below) the return value won't be used by the callback.
    //
    struct Implementor {
        using SharedPtr = std::shared_ptr<Implementor>;
        using WeakPtr   = std::weak_ptr<Implementor>;      

        using MessageCallback = void (*)( const SharedPtr &theImplementor, 
                                          Message         &theArguments, 
                                          Message         &theReturnValue );
     
        virtual ~Implementor() = default;
    };

    struct Client {
        using SharedPtr = std::shared_ptr<Client>;
        using WeakPtr   = std::weak_ptr<Client>;      

        virtual void implementorIsRegistered( const Implementor::SharedPtr &theImplementor ) = 0;

        virtual ~Client() = default;
    };

    //-------------------------------------------------------------------------    
    // REQUIRED
    // This class is used by the generated code to create a virtual table
    // for a receiver of messages. The generated code will never copy or
    // assign to instances of this type.You may wish to enforce this.
    //
    struct VTable {
        //---------------------------------------------------------------------
        // REQUIRED
        // The following add methods are called by the generated stubs when 
        // building up the virtual table.
        //
        template<typename theReturnType, typename...theArgumentTypes>
        VTable &
        addMethod( const char                                  *theMethodName, 
                   const typename Implementor::MessageCallback &theCallback );

        template<typename... theArgumentTypes>
        VTable &
        addSignal( const char                                  *theSignalName, 
                   const typename Implementor::MessageCallback &theCallback );
         
        //---------------------------------------------------------------------
        // REQUIRED
        // This method is called by the generated stubs when the virtual table 
        // is complete and the registered implementor is ready to receive 
        // messages.
        //
        [[gnu::weak]]
        void publish();
    
        VTable( const VTable &)             = delete;
        VTable( VTable &&)                  = delete;
        VTable &operator=( const VTable & ) = delete;
        VTable &operator=( VTable && )      = delete;

        //---------------------------------------------------------------------
        // Feel free to add constructors, members and methods of your needs.
        // The generated code only assumes the existence of the methods above.
        //
       [[gnu::weak]]
        VTable( Policy                       &thePolicy,
                const std::string            &theObjectPath,
                const std::string            &theInterfaceName,
                const Implementor::SharedPtr &theImplementor,
                bool                          isSignalInterface ); 
        
       [[gnu::weak]]
        ~VTable();


   private:
        friend struct Policy;

        [[gnu::weak]]
        bool requestBusnameForSignalInterface();

        const bool                                isSignalInterface;
        std::size_t                               itsSignalCounter;
        Policy                                   &itsPolicy;
        std::vector<sd_bus_slot*>                 itsSlots;
        const std::string                         itsObjectPath;
        const std::string                         itsInterfaceName;
        std::vector<Implementor::WeakPtr>         itsImplementors;
        std::vector<sd_bus_vtable>                itsSdbusVTable;
        std::vector<sd_bus_message_handler_t>     itsSignalCallbacks;
        std::vector<Implementor::MessageCallback> itsVTable;
        
        //---------------------------------------------------------------------
        [[gnu::weak]]
        VTable &
	addImplementor( Implementor::SharedPtr theNewImplementor );

        //---------------------------------------------------------------------
        [[gnu::weak]]
        std::size_t
	removeImplementor( const Implementor * const theOneToRemove );

        //---------------------------------------------------------------------
        [[gnu::weak]]
        VTable &
        addMethod( const char                                   *theMethodName,
		   const char                                   *theReturnType,
		   const char                                   *theSignature,
		   const typename Implementor::MessageCallback  &theCallback );

        //---------------------------------------------------------------------
        [[gnu::weak]]
        int 
        mainHandler( std::size_t     theVtableIndex,
                     sd_bus_message *theMessage, 
                     sd_bus_error   *theReturnedError );

        //---------------------------------------------------------------------
        template< int N >
        friend int ::babel::sdbus::internal::rawHandler( sd_bus_message *theMessage,
                                                         void           *theUserData,
                                                         sd_bus_error   *theReturnedError );
    };

    //-------------------------------------------------------------------------
    // REQUIRED
    // This method is used by the generated message receiving stubs when they 
    // are ready to build their virtual tables for an implementation. 
    // This method should return a VTable instance that the caller can use to 
    // register its methods.        
    // 
   [[gnu::weak]]
    VTable &
    registerImplementor( const char                  *theObjectPath,
                         const char                  *theInterfaceName, 
                         std::shared_ptr<Implementor> theImplementor );

    //-------------------------------------------------------------------------
    // REQUIRED
    // This method is used by the generated clients to inquire for local
    // implementations of the path and interface.
    // It should return a pointer to an existing implementation or null if
    // no such implementation exists. Should such an implementation be
    // known later, the client should be notified via the Client interface.
    // 
    [[gnu::weak]]
    Implementor::SharedPtr
    registerClient( const Client::WeakPtr &theClient, 
                    const char            *toServerAndObjectPath,
                    const char            *withInterface );

    //-------------------------------------------------------------------------
    // REQUIRED
    // This method is used by the generated message receiving stubs when they 
    // are ready to build their virtual tables for a signal listener. 
    // This method should return a VTable instance that the caller can use to 
    // register its listener calls.        
    // Note that several listeners may be added with the same path and
    // interface. 
    // 
   [[gnu::weak]]
    VTable &
    registerListener( const char                  *theObjectPath,
                      const char                  *theInterfaceName, 
                      std::shared_ptr<Implementor> theImplementor );

    //-------------------------------------------------------------------------
    // REQUIRED
    // This method will be used by the generated code when it no longer
    // wishes to receive messages.The method must guarantee that no more
    // calls may be pending when the method returns.
    //
   [[gnu::weak]]
    void 
    deregisterImplementor( const char        *theObjectPath,
                           const char        *theInterfaceName,
			   const Implementor *theImplementor);

    //-------------------------------------------------------------------------
    // REQUIRED
    // These methods are used by generated code when it encounters warning or
    // error situations. The generated code does not make any assumption of 
    // what the methods does with its printf-like arguments, except that the 
    // error method is not expected to return normally (i.e. it should either 
    // terminate the program or throw an exception). 
    //
    [[gnu::weak]] [[gnu::format(printf,1,2)]]
    static void 
    reportWarning( const char *theFormat, ... );
   
    [[noreturn]] [[gnu::weak]] [[gnu::format(printf,2,3)]]
    static void 
    reportError( int theErrNo, const char *theFormat, ... );
   
    //-------------------------------------------------------------------------
    // REQUIRED
    // This method will be used by generated code when it wants to create a 
    // message to be sent later when arguments have been appended.
    //
   [[gnu::weak]]
    Message 
    createMethodMessage( const char *theDestinationObjectPath,
			 const char *theInterface, 
			 const char *theMethod );
    
    //-------------------------------------------------------------------------
    // REQUIRED
    // This method will be used by generated code when it wants to create a 
    // message to be sent later when arguments have been appended.
    //
   [[gnu::weak]] 
    Message 
    createSignalMessage( const char *theSourceObjectPath,
			 const char *theInterface, 
			 const char *theSignal );
    
    //-------------------------------------------------------------------------
    // REQUIRED
    // This method will be used by generated code when it wants to read 
    // arguments attached to a message. The read is assumed to be "destructive",
    // i.e. the same arguments should be possible to read all at the same time
    // or one at a time by subsequent calls to this method.
    //
    template <typename MessageT, typename... theMessageArgumentTypes>
    static void 
    getMessageArguments( MessageT                    &&theMessage, 
                         theMessageArgumentTypes&&...  theMessageArguments );

    //-------------------------------------------------------------------------
    // REQUIRED
    // This method will be used by generated code when it wants to read an
    // array argument attached to a message. The element type will always be
    // "simple type", i.e. a C type where consecutive elements are stored at
    // the next address given by adding the size of the element to the address
    // of the previous element.
    // The read is assumed to be "destructive", i.e. the same arguments should 
    // be possible to read all at the same time or one at a time by subsequent 
    // calls to this method.
    // After a successful call the theNumberOfElements will contain the length
    // of the array (which may be 0) and theElements will point to the
    // (properly aligned) first object of the array.
    //
    template <typename MessageT, typename theElementType>
    static void 
    getMessageArray( MessageT             &&theMessage, 
                     const theElementType *&theElements,
		     std::size_t           &theNumberOfElements );

    //-------------------------------------------------------------------------
    // OPTIONAL
    // This method is used when generated code accesses received variant
    // message. It returns true if the message within an open variant
    // 
    template <typename MessageT, typename theMessageArgumentType>
    static bool 
    checkMessageVariantArgumentType( MessageT &&theMessage ); 
    
    //-------------------------------------------------------------------------
    // REQUIRED
    // This method is used when generated code wants to append arguments to 
    // a message.
    //
    template <typename MessageT, typename... theMessageArgumentTypes>
    static void 
    appendMessageArguments( MessageT                   &&theMessage, 
                            theMessageArgumentTypes...   theMessageArguments);

    
    //-------------------------------------------------------------------------
    // REQUIRED
    // This method will be used by generated code when it wants to write an
    // array argument to a message instance. The element type will always be
    // "simple type", i.e. a C type where consecutive elements are stored at
    // the next address given by adding the size of the element to the address
    // of the previous element.
    //
    template <typename MessageT, typename theElementType>
    static void 
    appendMessageArray( MessageT        &&theMessage, 
			theElementType *theElements,
			std::size_t     theNumberOfElements );

    //-------------------------------------------------------------------------
    // REQUIRED
    // This method is used to send a previously created method message. 
    // It is up to the caller to handle the return value (if any).
    // See also: createMethodMessage
    //
    template <typename MessageT>
    Message 
    sendMessage( MessageT &&theMessage );
    
    //-------------------------------------------------------------------------
    // REQUIRED
    // This method is used to emit a previously created signal message. 
    // See also: createSignalMessage
    //
    template <typename MessageT>
    void
    emitSignal( MessageT &&theMessage );
    
    //-------------------------------------------------------------------------
    // This method returns the underlying file descriptor of the bus
    // connection. Caveat emptor: The descriptor will be closed if the 
    // instance of the policy is deleted.
    //
    [[gnu::weak]]
    int getFileDescriptor() const;
    
    //-------------------------------------------------------------------------
    // This method returns the bus name which was used when
    // the policy was created or (if the supplied bus name was null upon
    // creation) the name assigned by the sd bus server.
  //
    [[gnu::weak]]
    std::string getItsBusName() const;

    //-------------------------------------------------------------------------
    // This method will run the main loop until an error occurs, the duration
    // has elapsed or the loop  is stopped by calling stopMainLoop();
    // The default argument means infinte duration.
    // 
    [[gnu::weak]]
    void runMainLoop( std::chrono::high_resolution_clock::duration  theDuration =
                              std::chrono::high_resolution_clock::duration::max() );

    //-------------------------------------------------------------------------
    // This method will asynchronously stop the main loop. Note that the event
    // loop may not stop immediately but need to wait until some bus activity
    // occurs. A stopped event loop cannot be started again.
    //
   [[gnu::weak]]
    void stopMainLoop();

    //-------------------------------------------------------------------------
    // This method will process pending events (see NotifyPendingEvents). 
    // This method will do nothing if the main loop is stopped before the call.
    //
    [[gnu::weak]]
    void processEvents();

    //-------------------------------------------------------------------------
    // This method will process ONE pending event. This method will do nothing 
    // if the main loop is stopped before call.
    // The method returns a value indicating the state of the main loop event 
    // queue.
    //
    enum class EventQueue {
       IsEmpty,
       HasMoreEvents,
       IsStopped
    };

    [[gnu::weak]]
    EventQueue 
    processEvent();

    [[gnu::weak]]
    ~Policy();

    //-------------------------------------------------------------------------
    // Make constructors of your choice as well as other data members and 
    // methods.
    // These are never used by generated code.
    //
    
    enum class Sdbus {
        System,
        Session
    };
   
    //-------------------------------------------------------------------------
    // The following callback funtions is invoked when any method in this 
    // policy has caused the underlying socket to have been read (e.g. 
    // a send method call) and buffered internally in the sdbus library
    // and thus a wait on the underlying socket will not detect that data
    // is avaiable for processing. Typically the callout implementation 
    // will ensure that the main loop is run by calling processEvents().
    //
    using NotifyPendingEvents = 
       std::function< void(const std::weak_ptr<Policy> &) >;
    
    [[gnu::weak]]
    static std::shared_ptr<Policy> 
    createPolicy( Sdbus                forTheBus, 
                  const char          *theBusName,
                  NotifyPendingEvents  theNotification );

    Policy( const Policy &)             = delete;
    Policy( Policy &&)                  = delete;
    Policy &operator=( const Policy & ) = delete;
    Policy &operator=( Policy && )      = delete;

private:
   friend struct VTable;

   using Bus    = std::unique_ptr<sd_bus,ManagedReleaser<sd_bus,sd_bus_unref>>;
   using Report = std::array< char, 256 >;
   
    //-------------------------------------------------------------------------
    // This exception class is used through-out to pass both a description
    // and a standard Unix error number.
    //
    struct Exception : public std::exception {
        int    itsErrNo;
        Report itsReport;
       
        [[gnu::weak]]
        const char *what() const noexcept override;
       
        [[gnu::weak]] 
        Exception( int theErrno );
       
        [[gnu::weak]] [[gnu::format(printf,3,4)]]
        Exception( int         theErrNo, 
                   const char *theFormat, 
                  ... );
    };

   [[gnu::weak]]
    Policy( Bus                 &theBus,
            const char          *theBusName,
            NotifyPendingEvents  theNotification );
   
    [[noreturn]] [[gnu::weak]]
    static void 
    throwError( const sd_bus_error &theError );
 
    enum struct BusNameStatus {
        Yes,
        No,
        UseDefault
    };

    const Bus                              itsBus;
    const std::string                      itsBusName;
    const NotifyPendingEvents              itsNotification;
    BusNameStatus                          itsBusNameIsRequested    = BusNameStatus::No;
    bool                                   itsDestructionIsUnderway = false;
    volatile bool                          itsStopEventLoopFlag     = false;


   // Accessor method to be used by the VTable class
   //
   sd_bus *getItsBus() const {
      return itsBus.get();
   }

   // Method to request the bus name of the policy unless it has 
   // already been done.
   //
   [[gnu::weak]]
   void requestBusName();

   struct ImplementorKey {
      const std::string itsObjectPath;
      const std::string itsInterfaceName;
      
      ImplementorKey( const char * theObjectPath,
                      const char * theInterfaceName ) :
         itsObjectPath( theObjectPath ),
         itsInterfaceName( theInterfaceName ){
      }

      bool operator==( const ImplementorKey &theOther ) const {
         return 
            (itsObjectPath    == theOther.itsObjectPath) &&
            (itsInterfaceName == theOther.itsInterfaceName);
      }

      bool operator<( const ImplementorKey &theOther) const {
         const auto theObjectPathComparison = 
            itsObjectPath.compare(theOther.itsObjectPath);
         
         if (theObjectPathComparison < 0) {
            return true;
         }
         else if (theObjectPathComparison == 0) {
            return itsInterfaceName < theOther.itsInterfaceName;
         }
         else {
            return false;
         }
      }
   };

   std::map     < ImplementorKey, std::unique_ptr< VTable>> itsImplementors;
   std::multimap< ImplementorKey, Client::WeakPtr>          itsClients;
};

