void 
Policy::throwError( const sd_bus_error &theError ) {
    // First check to see if it is a "transferred" C++ exception.
    //
    {
        static constexpr char        theIdTag[]  = "(std::";
        static constexpr std::size_t sizeOfIdTag = (sizeof(theIdTag) - 1);
        
        if (strncmp( theError.message, theIdTag, sizeOfIdTag) == 0) {
            const auto theExceptionName = theError.message + sizeOfIdTag;
            auto       theMessage    = index( theExceptionName, ')');
            
            if (theMessage) {
                const std::size_t theExceptionNameSize = 
                    theMessage - theExceptionName;
                
                while (*++theMessage == ' ') {}
                
                #define COM_SEASWORD_THROW_IF_MATCH( theException, theDbusError ) \
                do {                                                              \
                    static constexpr char thisName[] = #theException;             \
                    if ((theExceptionNameSize == (sizeof(thisName)-1)) &&         \
                            !strncmp( thisName,                                   \
                                      theExceptionName,                           \
                                      theExceptionNameSize )) {                   \
                        throw theDbusError{ theMessage, theError.name };          \
                    }                                                             \
                } while (0)

                COM_SEASWORD_THROW_IF_MATCH( domain_error,     DbusDomainError     );
                COM_SEASWORD_THROW_IF_MATCH( invalid_argument, DbusInvalidArgument );
                COM_SEASWORD_THROW_IF_MATCH( length_error,     DbusLengthError     );
                COM_SEASWORD_THROW_IF_MATCH( out_of_range,     DbusOutOfRange      );
                COM_SEASWORD_THROW_IF_MATCH( range_error,      DbusRangeError      );
                COM_SEASWORD_THROW_IF_MATCH( overflow_error,   DbusOverflowError   );
                COM_SEASWORD_THROW_IF_MATCH( underflow_error,  DbusUnderflowError  );
                COM_SEASWORD_THROW_IF_MATCH( runtime_error,    DbusRuntimeError    );
                COM_SEASWORD_THROW_IF_MATCH( logic_error,      DbusLogicError      );

                #undef COM_SEASWORD_THROW_IF_MATCH

                // The rest ( future_error, regex_error, system_error,
                // bad_cast, bad_weak_ptr, bad_function_call, bad_alloc,
                // bad_type_id & bad_exception) have non-trivial constructors. 
                // Fall through and examine the error number instead
                //
            }
        }
    }
    // Failing the check above, throw according to the error number
    //
    switch (std::abs(sd_bus_error_get_errno(&theError))) {
        case EDOM:
        case ERANGE:
            throw DbusDomainError{ theError };
        case EINVAL:
            throw DbusInvalidArgument{ theError };
        case EOVERFLOW:
            throw DbusOverflowError{ theError };
        case ENOMEM:
            throw DbusBadAlloc{};
        default:
            throw DbusRuntimeError{ theError };
    }
}

