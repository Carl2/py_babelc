// Short hand for removing adornments which doesn't matter for our
// type analysis
//
template <typename T>
struct cleaned_up {

  using precleaned_type = std::remove_reference_t< std::remove_cv_t< T > >;
  using type = 
    std::conditional_t< 
       (std::is_same<precleaned_type, const char*>::value ||
         std::is_same<precleaned_type, char *>::value),
       precleaned_type,
       std::conditional_t< 
          std::is_pointer<precleaned_type>::value,
          std::remove_pointer_t<precleaned_type>,
          precleaned_type 
        >
    >;
};


template <typename T>
using cleaned_up_t = typename cleaned_up<T>::type;

//=============================================================================
// The following structure is specialized to create 
// the dbus type string for arguments and return values and for interpreting
// actual parameters.
// A specialization is made for each supported type and structures and arrays
// of these. To distinguish these classes from each other, different base 
// classes are used:
//   BasicType is the template base class for the simple types passed on
//   the dbus protocol.
//   CompositeType is a composition of BasicTypes and they don't exists
//   on the dbus protocol other than as collection of BasicTypes.
//   SemanticType is a base class that is used for delimiters of the dbus
//   protocol.
// The base classes defines it's underlying type, TheType, as a tuple with one
// element of that type. If the specialization does not have a type it is a
// 'meta' type information e.g. the beginning of a structure or array.
// The type hierarchy also defines a compile time character constant that is its
// dbus protocol code. A type only has this field if it is present
// "on the wire", i.e. the TypeInfo for a structure does not have any, but it
// is instead expanded into its atoms recursively and enclosed in the atoms for
// a structure start and end (which thus belong to the SemanticType category).
//
template <typename theUnderlyingType, char theCode > struct BasicType {
    using is_basic_type        = std::true_type;
    using is_fixed_size        = std::conditional_t< theCode == 's', std::false_type, std::true_type >;
    using TheType              = std::conditional_t< std::is_same<theUnderlyingType,void>::value, std::tuple<>, std::tuple< theUnderlyingType > >;
    static constexpr char Code = theCode;
};

template <typename theUnderlyingType, char theCode > struct CompositeType {
    using is_basic_type                 = std::false_type;
    using is_fixed_size                 = std::false_type;
    using TheType                       = theUnderlyingType;
    static constexpr char ContainerCode = theCode;
};

template < char theCode > struct SemanticType {
    using is_basic_type        = std::false_type;
    using is_fixed_size        = std::false_type;
    static constexpr char Code = theCode;
};


// Types defining SemanticType atoms
