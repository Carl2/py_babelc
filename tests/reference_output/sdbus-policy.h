template <> struct TypeInfo< std::int32_t    > : BasicType   < std::int32_t,    'i'  > {};
template <> struct TypeInfo< std::uint32_t   > : BasicType   < std::uint32_t,   'u'  > {};
template <> struct TypeInfo< std::int64_t    > : BasicType   < std::int64_t,    'x'  > {};
