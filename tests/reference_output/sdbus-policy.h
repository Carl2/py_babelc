template<typename theReturnType, typename...theArgumentTypes>
inline Policy::VTable &
Policy::VTable::addMethod( 
    const char                                  *theMethodName, 
    const typename Implementor::MessageCallback &theCallback) {

    if (isSignalInterface) {
       Policy::reportError( EINVAL, 
                            "Attempt to add method to signal interface %s",
                            itsInterfaceName.c_str() );
    }

    return addMethod( theMethodName, 
                      Signature<ParameterListClass<theReturnType> >::value,
                      Signature<ParameterListClass<theArgumentTypes...>>::value,
                      theCallback );
}

//=============================================================================

template<typename... theArgumentTypes>
inline Policy::VTable &
Policy::VTable::addSignal( 
    const char                                  *theSignalName, 
    const typename Implementor::MessageCallback &theCallback ) {
    
    if ( ! isSignalInterface) {
       Policy::reportError( EINVAL, 
                            "Attempt to add signal to method interface %s",
                            itsInterfaceName.c_str() );
    }
    return addMethod( theSignalName, 
                      "",
                      Signature<ParameterListClass<theArgumentTypes...>>::value,
                      theCallback );
}
         
