bool
Policy::VTable::requestBusnameForSignalInterface() {
  if (itsSignalCallbacks.empty()) {
      // This is a method interface, which means that
      // we need to have the bus name registered.
      //
      itsPolicy.requestBusName();
      return true;
  }
  else {
    return false;
  }
}

