void 
Policy::reportWarning( const char *theFormat, ... ) {
    va_list theArguments;
    Report  theReport;
    
    va_start(theArguments, theFormat);
    (void)vsnprintf( &theReport.front(), 
                     theReport.size(), 
                     theFormat, 
                     theArguments );
    theReport.back() = '\0'; // Better safe than sorry...
    babel::sdbus::reportWarning(&theReport.front());
    va_end(theArguments);
}

