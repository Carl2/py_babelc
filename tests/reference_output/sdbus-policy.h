// A parameter list is defined as the concatenated tuples of all
// TypeInfos for the template arguments. 
// In essence this produces a flattened tuple of all atoms with structure and
// array information in-lined - in short: a dbus type string definition.
//
template <typename... T> 
struct TypeInfo< ParameterList, T... > 
  : CompositeType<decltype(std::tuple_cat( PlainTypeInfo<T>()... )), '\0' >
{};

// This type is used so often that a helper comes in handy:
//
template <typename... T>
using ParameterListClass = typename TypeInfo< ParameterList, T...>::TheType;

