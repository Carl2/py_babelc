// This is a very simple deleter functor for a smart pointer
// to the various sd bus managed types
//
template < typename ManagedType, ManagedType *(*Releaser)( ManagedType * ) >
struct ManagedReleaser {
   void operator()( ManagedType *theManagedObjectPtr ) {
      (void)(*Releaser)( theManagedObjectPtr );
   }
};

