void 
Policy::reportError( int theErrNo, const char *theFormat, ... ) {
    Exception  theException( theErrNo );  
    Report    &theReport = theException.itsReport;
    va_list    theArguments;
    
    va_start(theArguments, theFormat);
    (void)vsnprintf( &theReport.front(), 
                     theReport.size(), 
                     theFormat, 
                     theArguments );
    theReport.back() = '\0'; // Better safe than sorry...
    babel::sdbus::reportError(&theReport.front());
    va_end(theArguments);

    throw theException;
}
   
