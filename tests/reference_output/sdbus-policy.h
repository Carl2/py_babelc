inline Policy::Message 
Policy::createMethodMessage( const char *theDestinationObjectPath,
                     const char *theInterface, 
                     const char *theMethod ) {

    using namespace std::literals::string_literals;

    const char * const theColon = std::strchr( theDestinationObjectPath, ':' );

    if (theColon == nullptr) {
       throw std::invalid_argument( "Destination lacks service name: "s +
                                    theDestinationObjectPath );
    }

    const std::string  theServiceName(theDestinationObjectPath, theColon);
    sd_bus_message    *theRawMessage  = nullptr;

    COM_SEASWORD_SDBUS_CHECK( 
       sd_bus_message_new_method_call(
          itsBus.get(), 
	  &theRawMessage, 
	  theServiceName.c_str(),
	  (theColon + 1),         // The object path
	  theInterface, 
	  theMethod 
       )
    );

    return Message( theRawMessage );
}
    
