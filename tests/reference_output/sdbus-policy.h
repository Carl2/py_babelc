// Macros when they are needed - to get at location info
//
#define COM_SEASWORD_SDBUS_CHECK( theCondition )                            \
do {                                                                        \
  const int theError = (theCondition);                                      \
  if (theError < 0) {                                                       \
      Policy::reportError( -theError, "%s:%d (%d) %s", __FILE__, __LINE__,  \
			   -theError, #theCondition );			    \
  }                                                                         \
} while (0)

#define COM_SEASWORD_SDBUS_CHECK_WITH_WARNING( warningList, theCondition )   \
do {                                                                         \
  static const int theWarnings[] = warningList;                              \
  const int        theError      = (theCondition);                           \
  if (theError < 0) {                                                        \
    if (std::find(std::begin(theWarnings),std::end(theWarnings),-theError) !=\
          std::end(theWarnings)) {                                           \
      Policy::reportWarning( "%s:%d (%d) %s", __FILE__, __LINE__,            \
			     -theError, #theCondition );		     \
    }                                                                        \
    else {                                                                   \
      Policy::reportError( -theError, "%s:%d (%d) %s", __FILE__, __LINE__,   \
			   -theError, #theCondition );			     \
    }                                                                        \
  }                                                                          \
} while (0)


