Policy::VTable &
Policy::registerImplementor( const char                  *theObjectPath,
                             const char                  *theInterfaceName, 
                             std::shared_ptr<Implementor> theImplementor ) {
    
  const ImplementorKey theKey(theObjectPath, theInterfaceName );
  const auto theInsertionResult = itsImplementors.insert( 
      std::make_pair( 
         theKey,
	 std::unique_ptr<VTable>(
	    new VTable( 
		*this,
		theObjectPath,
		theInterfaceName,
		theImplementor,
		false
            )
          )
       )   
  );
    
  if (theInsertionResult.second) {
    const auto theClients = itsClients.equal_range( theKey );
    auto       theClient  = theClients.first;

    while (theClient != theClients.second) {
      if (auto theClientPtr = theClient->second.lock()) {
	// Let  the client know!
	//
	theClientPtr->implementorIsRegistered(theImplementor);
	theClient++;
      }
      else {
	// Prune dead clients
	//
	theClient = itsClients.erase(theClient);
      }
    }

    return *theInsertionResult.first->second;
  }
  else {
    reportError( EINVAL, 
		 "Interface %s:%s already registered",
		 theObjectPath,
		 theInterfaceName );
  }    
}

Policy::VTable &
Policy::registerListener( const char                  *theObjectPath,
			  const char                  *theInterfaceName, 
			  std::shared_ptr<Implementor> theImplementor ) {

  const ImplementorKey theKey( theObjectPath, theInterfaceName );
  const auto           thePreviousListener( itsImplementors.find( theKey ) );

  if (thePreviousListener == itsImplementors.end ()) {
    // Insertion will always succeed
    //
    return *itsImplementors.insert( 
	       std::make_pair( theKey,
			       std::make_unique<VTable>(
				   *this,
				   theObjectPath,
				   theInterfaceName,
				   theImplementor,
				   true
				)
	       )
	    ).first->second;   
  }
  else if (thePreviousListener->second->isSignalInterface) {
    return thePreviousListener->second->addImplementor( theImplementor );
  }
  else {
    reportError( EINVAL, 
		 "Interface %s is already registered as a method interface",
		 theInterfaceName );
  }
}

//=============================================================================
Policy::Implementor::SharedPtr
Policy::registerClient( const Client::WeakPtr &theClient, 
			const char            *toServerAndObjectPath,
			const char            *withInterface ) {
  
  const char * const theColon = std::strchr( toServerAndObjectPath, ':' );
  
  // If there is no server name or the server name does not
  // equal the bus name, return an empty pointer
  //
  if ((theColon == nullptr) || 
       std::strncmp( toServerAndObjectPath, 
		     itsBusName.c_str(), 
		     (theColon - toServerAndObjectPath))) {
    return Policy::Implementor::SharedPtr();
  }
  else {
    const ImplementorKey theKey( (theColon + 1), withInterface );

    itsClients.insert( std::make_pair( theKey, theClient ) );

    const auto theImplementor = itsImplementors.find(theKey);

    if (theImplementor == itsImplementors.end()) {
      return Policy::Implementor::SharedPtr();
    }
    else {
      const VTable &theVTable = *theImplementor->second;

      if (theVTable.isSignalInterface) {
	reportError( EINVAL, "Interface %s:%s is not a server",
		     toServerAndObjectPath, 
		     withInterface );
      }

      return theVTable.itsImplementors[0].lock();
    }
  }
}

//=============================================================================
void 
Policy::deregisterImplementor( const char        *theObjectPath, 
                               const char        *theInterfaceName,
			       const Implementor *theImplementor ) {

   if (!itsDestructionIsUnderway) {
       const ImplementorKey theKey( theObjectPath, theInterfaceName );

       auto theElement = itsImplementors.find( theKey );

       if (theElement == itsImplementors.end()) {
           reportError( EINVAL, 
                        "Failed to erase implementor %s:%s", 
                        theInterfaceName,
                        theInterfaceName );
       }
       else if (theElement->second->removeImplementor(theImplementor) == 0) {
           // No more implementors for this one => get rid of it
           //
           itsImplementors.erase( theElement );
       }
   }
}


