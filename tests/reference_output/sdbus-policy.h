template <typename Tuple, std::size_t ...Indices>
void writeTuple( sd_bus_message      *theMessage, 
                 Tuple&&              theTuple, 
                 std::index_sequence< Indices...> ) {
    COM_SEASWORD_SDBUS_CHECK(
        sd_bus_message_open_container( 
            theMessage, 
            SD_BUS_TYPE_STRUCT, 
            Signature< 
                ParameterListClass<std::tuple_element_t<Indices,cleaned_up_t<Tuple>>...>
            >::value
        )
    );
    
    writeArgs(theMessage, std::get<Indices>(std::forward<Tuple>(theTuple))...);
  
    COM_SEASWORD_SDBUS_CHECK(
        sd_bus_message_close_container( theMessage )
    );
}

template <typename T, typename... R> 
std::enable_if_t< is_basic_type_t<T>::value && 
                  conjunction< is_basic_type_t<R>... >::value >
writeArgs( sd_bus_message *theMessage, T&& theFirst, R&&... theRest ) {
  appendArguments(theMessage, theFirst, theRest...);
}

template <typename T, typename... R> 
std::enable_if_t< is_basic_type_t<T>::value && 
                  !conjunction< is_basic_type_t<R>... >::value >
writeArgs( sd_bus_message *theMessage, T&& theFirst, R&&... theRest ) {
  appendArguments( theMessage, theFirst);
  writeArgs( theMessage, theRest... );
}

template <typename T, typename... R> 
std::enable_if_t< is_instantiation<cleaned_up_t<T>, std::tuple>::value >
writeArgs( sd_bus_message *theMessage, T&& theFirst, R&&... theRest ) {
  writeTuple( theMessage, 
              theFirst, 
              std::make_index_sequence<std::tuple_size<std::decay_t<T>>{}>{} );
  writeArgs( theMessage, theRest... );
}

template <typename T, typename...R > 
std::enable_if_t< is_array<cleaned_up_t<T>>::value && 
                  is_fixed_size_t<typename cleaned_up_t<T>::value_type>::value>
writeArgs( sd_bus_message *theMessage, T&& theArray, R&&... theRest ) {
    using ElementType = typename cleaned_up_t<T>::value_type;

    COM_SEASWORD_SDBUS_CHECK(
        sd_bus_message_append_array( 
                theMessage, 
                TypeInfo<ElementType>::Code,
                &theArray.front(), 
                (theArray.size() * sizeof(ElementType))
        )
    );

    writeArgs( theMessage, theRest... );
}

template <typename T, typename...R > 
std::enable_if_t<is_array<cleaned_up_t<T>>::value && 
                 !is_fixed_size_t<typename cleaned_up_t<T>::value_type>::value>
writeArgs( sd_bus_message *theMessage, T&& theArray, R&&... theRest ) {
    COM_SEASWORD_SDBUS_CHECK(
        sd_bus_message_open_container( 
                theMessage, 
                SD_BUS_TYPE_ARRAY, 
                Signature< 
                    ParameterListClass< typename cleaned_up_t<T>::value_type >
                >::value
        )
    );

    for (std::size_t i = 0; i < theArray.size(); i++) {
      writeArgs( theMessage, theArray[i] );
    }

    COM_SEASWORD_SDBUS_CHECK(
        sd_bus_message_close_container( theMessage )
    );

    writeArgs( theMessage, theRest... );
}


