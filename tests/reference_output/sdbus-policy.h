template <typename T>
T* getAddress( T& t ) { 
  return &t; 
}

template <typename T>
T* getAddress( T* t ) { 
  return t; 
}

template <typename Tuple, std::size_t ...Indices>
void readTuple( sd_bus_message      *theMessage, 
                Tuple*               theTuple, 
                std::index_sequence< Indices...> ) {
    COM_SEASWORD_SDBUS_CHECK(
        sd_bus_message_enter_container( 
            theMessage, 
            SD_BUS_TYPE_STRUCT, 
            Signature< 
                ParameterListClass<
                    std::remove_pointer_t<std::tuple_element_t<Indices,cleaned_up_t<Tuple>>>...
                >
            >::value
        )
    );
    
    readArgs(theMessage, getAddress(std::get<Indices>(*theTuple))...);
  
    COM_SEASWORD_SDBUS_CHECK(
        sd_bus_message_exit_container( theMessage )
    );
}

